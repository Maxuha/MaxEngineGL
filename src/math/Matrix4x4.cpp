#include "Matrix4x4.h"

Matrix4x4::Matrix4x4(float value) {
    if (value == 0) {
        m[0][0] = 0;
        m[1][0] = 0;
        m[2][0] = 0;
        m[3][0] = 0;
        m[0][1] = 0;
        m[1][1] = 0;
        m[2][1] = 0;
        m[3][1] = 0;
        m[0][2] = 0;
        m[1][2] = 0;
        m[2][2] = 0;
        m[3][2] = 0;
        m[0][3] = 0;
        m[1][3] = 0;
        m[2][3] = 0;
        m[3][3] = 0;
    } else if (value == 1) {
        m[0][0] = 1;
        m[1][1] = 1;
        m[2][2] = 1;
        m[3][3] = 1;
    } else {
        m[0][0] = 0;
        m[1][0] = 0;
        m[2][0] = 0;
        m[3][0] = 0;
        m[0][1] = 0;
        m[1][1] = 0;
        m[2][1] = 0;
        m[3][1] = 0;
        m[0][2] = 0;
        m[1][2] = 0;
        m[2][2] = 0;
        m[3][2] = 0;
        m[0][3] = 0;
        m[1][3] = 0;
        m[2][3] = 0;
        m[3][3] = 0;
    }
}
