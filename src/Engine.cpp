void Engine::SaveDepthTextureToFile(GLuint textureId, int width, int height, const std::string& filename) {
    // 1. ???????? ????? ??? ?????? ??????? (???? ????? ???? float ?? ???????)
    std::vector<float> depthData(width * height);

    // 2. ?????? ?????? ?? ???????? ? RAM (?????????? Direct State Access ??? OpenGL 4.5+)
    glGetTextureImage(textureId, 0, GL_DEPTH_COMPONENT, GL_FLOAT, depthData.size() * sizeof(float), depthData.data());

    // 3. ????? ????? ?????? ???????? ? ????????? [0.0, 1.0].
    // ????? ????????? ?? ??? ??????? ????????, ????????? float ? ?????.
    std::vector<uint8_t> byteData(width * height);
    for (size_t i = 0; i < depthData.size(); ++i) {
        // ???????????: ???? ????? ??????? ??????? ?????, ????? ????????????? ???????,
        // ?? ??? ??????? ??????? ?????????? ???????? ??????????:
        byteData[i] = static_cast<uint8_t>(depthData[i] * 255.0f);
    }

    // 4. ?????????????? ???????? ?? ????????? (? OpenGL ???????? ???? ????? ?????, ? ? PNG ? ?????? ????)
    std::vector<uint8_t> flippedData(width * height);
    for (int y = 0; y < height; ++y) {
        std::memcpy(&flippedData[(height - 1 - y) * width], &byteData[y * width], width);
    }

    // 5. ?????????? ? ???? (1 ????? ? ??? Grayscale ???????????)
    int success = stbi_write_png(filename.c_str(), width, height, 1, flippedData.data(), width);

    if (success) {
        std::cout << "???????? ??????? ????????? ?: " << filename << std::endl;
    } else {
        std::cerr << "?? ??????? ????????? ????????!" << std::endl;
    }
}
